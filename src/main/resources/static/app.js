let currentLang = "en";
let currentUser = JSON.parse(localStorage.getItem("ecoUser"));
let chartInstance = null;

function applyLanguage(lang) {
    currentLang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (I18N[lang][key]) el.textContent = I18N[lang][key];
    });
    if (currentUser) loadDashboard();
}

document.getElementById("langSelect").addEventListener("change", e => applyLanguage(e.target.value));

document.getElementById("loginTab").addEventListener("click", () => {
    document.getElementById("loginForm").classList.remove("hidden");
    document.getElementById("registerForm").classList.add("hidden");
    document.getElementById("loginTab").classList.add("active");
    document.getElementById("registerTab").classList.remove("active");
});

document.getElementById("registerTab").addEventListener("click", () => {
    document.getElementById("registerForm").classList.remove("hidden");
    document.getElementById("loginForm").classList.add("hidden");
    document.getElementById("registerTab").classList.add("active");
    document.getElementById("loginTab").classList.remove("active");
});

document.getElementById("applianceSelect").addEventListener("change", e => {
    const selected = e.target.options[e.target.selectedIndex];
    document.getElementById("wattageInput").value = selected.getAttribute("data-watt");
});

document.getElementById("registerForm").addEventListener("submit", async e => {
    e.preventDefault();
    const res = await fetch("/api/register", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
            username: document.getElementById("regUsername").value,
            password: document.getElementById("regPassword").value,
            householdName: document.getElementById("regHousehold").value,
            familyMembers: parseInt(document.getElementById("regMembers").value, 10),
            city: document.getElementById("regCity").value
        })
    });
    if (res.ok) {
        currentUser = await res.json();
        localStorage.setItem("ecoUser", JSON.stringify(currentUser));
        showDashboard();
    } else {
        alert("Username already exists!");
    }
});

document.getElementById("loginForm").addEventListener("submit", async e => {
    e.preventDefault();
    const res = await fetch("/api/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
            username: document.getElementById("loginUsername").value,
            password: document.getElementById("loginPassword").value
        })
    });
    if (res.ok) {
        currentUser = await res.json();
        localStorage.setItem("ecoUser", JSON.stringify(currentUser));
        showDashboard();
    } else {
        alert("Invalid username or password!");
    }
});

document.getElementById("logoutBtn").addEventListener("click", () => {
    localStorage.removeItem("ecoUser");
    location.reload();
});

document.getElementById("printBtn").addEventListener("click", () => window.print());

document.getElementById("applianceForm").addEventListener("submit", async e => {
    e.preventDefault();
    await fetch("/api/appliances", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
            userId: currentUser.id,
            monthYear: document.getElementById("monthInput").value,
            applianceName: document.getElementById("applianceSelect").value,
            wattage: parseFloat(document.getElementById("wattageInput").value),
            quantity: parseInt(document.getElementById("quantityInput").value, 10),
            hoursPerDay: parseFloat(document.getElementById("hoursInput").value)
        })
    });
    loadDashboard();
});

async function loadDashboard() {
    const res = await fetch(`/api/report/${currentUser.id}`);
    const data = await res.json();

    document.getElementById("houseTitle").textContent = currentUser.householdName;
    document.getElementById("memberCount").textContent = currentUser.familyMembers;
    document.getElementById("cityName").textContent = currentUser.city;
    document.getElementById("perCapitaValue").textContent = `${data.perCapitaCo2} kg`;

    document.getElementById("reportBody").innerHTML = data.logs.map(log => `
        <tr>
            <td>${log.monthYear}</td>
            <td>${log.applianceName}</td>
            <td>${log.quantity}</td>
            <td>${log.hoursPerDay}</td>
            <td>${log.monthlyKwh}</td>
            <td><strong>${log.co2Kg}</strong></td>
        </tr>
    `).join("");

    document.getElementById("ecoSuggestionsList").innerHTML = data.suggestions
        .map(key => `<li>${I18N[currentLang][key] || key}</li>`)
        .join("");

    const ctx = document.getElementById("comparisonChart");
    if (chartInstance) chartInstance.destroy();
    chartInstance = new Chart(ctx, {
        type: "bar",
        data: {
            labels: Object.keys(data.monthlyCo2),
            datasets: [{
                label: I18N[currentLang].co2Kg,
                data: Object.values(data.monthlyCo2),
                backgroundColor: "#16a34a",
                borderRadius: 6
            }]
        },
        options: { responsive: true, maintainAspectRatio: false }
    });
}

function showDashboard() {
    document.getElementById("authSection").classList.add("hidden");
    document.getElementById("dashboardSection").classList.remove("hidden");
    document.getElementById("logoutBtn").classList.remove("hidden");
    loadDashboard();
}

if (currentUser) showDashboard();